// Травмы и ограничения.
//
// Человек пишет их свободным текстом: «болит поясница, не делаю становую».
// По-настоящему разобрать такую фразу может только модель — ей текст и
// уходит целиком (мастер ИИ, чат тренера, воркер). Здесь задача скромнее:
// подобрать замену упражнения без ИИ, прямо на странице тренировки, и хотя
// бы не ставить первым то, о чём человек прямым текстом попросил.
//
// Отсюда два решения. Первое — сравниваем не слова, а их начала: русские
// окончания («становую» против «Становая») иначе не совпадут никогда, а
// тащить в приложение полноценный стеммер ради одного поля незачем.
// Второе — совпадение только опускает упражнение в конец списка и помечает
// его, но никогда не прячет: усечение до основы иногда ловит лишнее, и цена
// ошибки должна быть «предупредили», а не «спрятали замену».

import { exerciseName, translateMuscle, translateEquipment } from './translate.js'

// Четыре буквы — компромисс: «плечо» и «плечи» сходятся только на «плеч»,
// а более короткая основа начинает цеплять всё подряд.
const STEM_LENGTH = 4
const MIN_WORD = 4

// Слова, которые есть почти в любой жалобе и не указывают ни на упражнение,
// ни на группу мышц. Без этого списка «болит» совпадало бы само с собой в
// любом тексте и ничего не значило.
const STOP_WORDS = [
  'болит', 'болят', 'боль', 'больно', 'нельзя', 'можно', 'делаю', 'делать',
  'после', 'травма', 'очень', 'если', 'когда', 'тяжело', 'сильно', 'только',
  'кроме', 'иногда', 'немного', 'есть', 'было', 'была', 'будет', 'надо',
  'нужно', 'хочу', 'могу', 'плохо', 'лучше', 'хуже', 'врач', 'месяц',
  'неделя', 'назад', 'сейчас', 'вообще', 'совсем', 'поэтому',
]

const stem = (word) => word.slice(0, STEM_LENGTH)

const STOP_STEMS = new Set(STOP_WORDS.map(stem))

// Одна нормализация на обе стороны сравнения: и текст ограничений, и
// название упражнения проходят через неё, иначе основы не сойдутся.
function stems(text) {
  if (!text) return []
  return String(text)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^a-zа-я0-9]+/)
    .filter((word) => word.length >= MIN_WORD)
    .map(stem)
}

/**
 * Основы значимых слов из текста ограничений — то, чего человек просил
 * избегать. Пустой список означает «ограничений нет».
 */
export function parseLimits(text) {
  return [...new Set(stems(text).filter((word) => !STOP_STEMS.has(word)))]
}

/**
 * Упоминается ли упражнение в ограничениях. Смотрим не только на название,
 * но и на группу мышц со снарядом: «болит поясница» — это про группу мышц,
 * а «без штанги» — про инвентарь, и оба случая человек пишет одинаково.
 */
export function conflictsWithLimits(exercise, avoid) {
  if (!avoid?.length || !exercise) return false
  const haystack = new Set(
    stems(
      [
        exerciseName(exercise),
        translateMuscle(exercise.muscleGroup),
        translateEquipment(exercise.equipment),
      ].join(' '),
    ),
  )
  return avoid.some((word) => haystack.has(word))
}
